(function injetarSprite() {
  const simbolos = Object.entries(ICONES)
    .map(([nome, desenho]) => `<symbol id="i-${nome}" viewBox="0 0 24 24">${desenho}</symbol>`)
    .join("");
  document.body.insertAdjacentHTML(
    "afterbegin",
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">${simbolos}</svg>`
  );
})();

// HTML de um ícone. "classe" permite tamanhos/cores extras (ex.: "ico-lg").
